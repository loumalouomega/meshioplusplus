#!/usr/bin/env python3
"""Generate the pipeline step tables of both engines from one spec.

``tools/pipeline_steps.json`` lists every pipeline step, its keys in the order
the docs and the errors give them, and for each key the kind (``number``,
``flag``, ``text``) and default both engines read it with. This script writes

* ``src/python/meshioplusplus/_pipeline_table.py`` (``OP_TABLE``,
  ``V2_STEPS``, ``V2_EXTRA_KEYS``), which ``_pipeline.py`` reads, and
* ``src/cpp/src/operations/pipeline_table.hpp`` (``pipe_op_table()``,
  ``pipe_v2_steps()``, ``pipe_v2_extra_keys()``), which ``pipeline.cpp`` reads,

so the two step tables are one list (roadmap §7).
``tests/python/test_pipeline_spec.py`` holds the steps' option parsing in
both languages to the spec's kinds and defaults.

    python tools/gen_pipeline_table.py            # rewrite both tables
    python tools/gen_pipeline_table.py --check    # exit 1 if either is out of date
"""

import argparse
import json
import pathlib
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "tools" / "pipeline_steps.json"
PY_OUT = ROOT / "src" / "python" / "meshioplusplus" / "_pipeline_table.py"
CPP_OUT = ROOT / "src" / "cpp" / "src" / "operations" / "pipeline_table.hpp"

_BANNER = (
    "Generated by tools/gen_pipeline_table.py from tools/pipeline_steps.json; "
    "do not edit."
)


def load_spec(path=SPEC):
    return json.loads(path.read_text(encoding="utf-8"))


def _py_keys(keys):
    names = [k["name"] for k in keys]
    if not names:
        return "()"
    if len(names) == 1:
        return f'("{names[0]}",)'
    return "(\n" + "".join(f'        "{n}",\n' for n in names) + "    )"


def python_table(spec):
    out = [
        f'"""{_BANNER}',
        "",
        "The pipeline step tables (roadmap §7). The C++ engine's twin is",
        'src/cpp/src/operations/pipeline_table.hpp, generated from the same spec."""',
        "",
    ]
    out.append("# Every step's keys, in order.")
    out.append("OP_TABLE = {")
    for st in spec["steps"]:
        if "note" in st:
            out += textwrap.wrap(
                st["note"], 96, initial_indent="    # ", subsequent_indent="    # "
            )
        out.append(f'    "{st["op"]}": {_py_keys(st["keys"])},')
    out.append("}")
    out.append("")
    out.append("# The steps only a version 2 file has.")
    out.append("V2_STEPS = {")
    for st in spec["v2_steps"]:
        out.append(f'    "{st["op"]}": {_py_keys(st["keys"])},')
    out.append("}")
    out.append("")
    out.append("# The keys a version 2 file adds to a step.")
    out.append("V2_EXTRA_KEYS = {")
    for op, keys in spec["v2_extra_keys"].items():
        out.append(f'    "{op}": {_py_keys([{"name": k} for k in keys])},')
    out.append("}")
    out.append("")
    out.append("# Each step's keys with a kind ('number', 'flag', 'text') and default,")
    out.append("# in order: what the ParaView plugin's filters expose as properties.")
    out.append("KEY_DEFAULTS = {")
    for st in spec["steps"] + spec["v2_steps"]:
        rows = []
        for k in st["keys"]:
            if "kind" not in k:
                continue
            default = k["default"]
            text = json.dumps(default) if isinstance(default, str) else repr(default)
            rows.append(f'("{k["name"]}", "{k["kind"]}", {text})')
        if len(rows) == 1:
            out.append(f'    "{st["op"]}": ({rows[0]},),')
        elif rows:
            out.append(f'    "{st["op"]}": (')
            out += [f"        {row}," for row in rows]
            out.append("    ),")
    out.append("}")
    return "\n".join(out) + "\n"


def _cpp_row(op, names):
    """One `{"Op", {"Key", ...}},` row, wrapped at 100 columns."""
    one = f'        {{"{op}", {{' + ", ".join(f'"{n}"' for n in names) + "}},"
    if len(one) <= 100:
        return [one]
    lines = [f'        {{"{op}",']
    cur = "         {"
    for i, n in enumerate(names):
        piece = f'"{n}"' + (", " if i + 1 < len(names) else "}},")
        if len(cur) + len(piece.rstrip()) > 100:
            lines.append(cur.rstrip())
            cur = "          "
        cur += piece
    lines.append(cur)
    return lines


def cpp_table(spec):
    out = [
        "// " + _BANNER,
        "#pragma once",
        "",
        "/**",
        " * @file operations/pipeline_table.hpp",
        " * @brief The pipeline step tables (roadmap §7): every step's keys, in order.",
        " *",
        " * A **core-private** header, included by pipeline.cpp only. The Python",
        " * engine's twin is `_pipeline_table.py`, generated from the same spec.",
        " */",
        "",
        "#include <string>",
        "#include <utility>",
        "#include <vector>",
        "",
        "namespace meshioplusplus {",
        "namespace detail {",
        "",
        "struct PipeOpSpec {",
        "    const char* mName;",
        "    std::vector<const char*> mKeys;",
        "};",
        "",
        "/// Every step a version 1 or 2 file has, with its keys.",
        "inline const std::vector<PipeOpSpec>& pipe_op_table() {",
        "    // clang-format off",
        "    static const std::vector<PipeOpSpec> table = {",
    ]
    for st in spec["steps"]:
        if "note" in st:
            out += textwrap.wrap(
                st["note"],
                100,
                initial_indent="        // ",
                subsequent_indent="        // ",
            )
        out += _cpp_row(st["op"], [k["name"] for k in st["keys"]])
    out += ["    };", "    // clang-format on", "    return table;", "}", ""]
    out += [
        "/// The steps only a version 2 file has.",
        "inline const std::vector<PipeOpSpec>& pipe_v2_steps() {",
        "    // clang-format off",
        "    static const std::vector<PipeOpSpec> table = {",
    ]
    for st in spec["v2_steps"]:
        out += _cpp_row(st["op"], [k["name"] for k in st["keys"]])
    out += ["    };", "    // clang-format on", "    return table;", "}", ""]
    out += [
        "/// The keys a version 2 file adds to a step.",
        "using PipeExtraKeys = std::vector<std::pair<std::string, std::vector<std::string>>>;",
        "",
        "inline const PipeExtraKeys& pipe_v2_extra_keys() {",
        "    // clang-format off",
        "    static const PipeExtraKeys table = {",
    ]
    for op, keys in spec["v2_extra_keys"].items():
        out += _cpp_row(op, keys)
    out += [
        "    };",
        "    // clang-format on",
        "    return table;",
        "}",
        "",
        "}  // namespace detail",
        "}  // namespace meshioplusplus",
    ]
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args(argv)
    spec = load_spec()
    wanted = {PY_OUT: python_table(spec), CPP_OUT: cpp_table(spec)}
    stale = [
        p
        for p, text in wanted.items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for p in stale:
            print(
                f"{p.relative_to(ROOT)} is out of date; run tools/gen_pipeline_table.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    for p in stale:
        p.write_text(wanted[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
