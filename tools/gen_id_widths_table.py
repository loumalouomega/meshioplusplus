"""Render ``doc/id_widths.md``: what each writable format does with ids above 2**31.

The outcomes are observed by ``tests/python/id_widths_spec.py`` (see its docstring
for the vocabulary) and declared in its :data:`EXPECTED` table; this script writes
the declarations as a page, and ``--observe`` prints the observed table in the
declaration's syntax so an intended change is a reviewed diff::

    python tools/gen_id_widths_table.py            # rewrite the page
    python tools/gen_id_widths_table.py --check    # exit 1 if it is stale
    python tools/gen_id_widths_table.py --observe  # print observed EXPECTED entries
"""

from __future__ import annotations

import argparse
import pathlib
import pprint
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tests" / "python"))

PAGE = REPO / "doc" / "id_widths.md"

HEADER = """# Integer widths of the writable formats

Generated by `tools/gen_id_widths_table.py` from `tests/python/id_widths_spec.py`; do not edit by hand.

Every writable format is given one mesh, with an int64 point array and an int64 cell array whose values are `2**31 + 5` and up (a node or cell tag above what a 32-bit integer holds), and the table says what came back. The mesh uses the cell types the format's row of the [conformance matrix](./conformance.md) declares.

- **exact** the same integers came back, as the dtype named.
- **double** the format stores the values as floating point and they came back equal.
- **single (exact)** the format stores single-precision floats and these particular values survived.
- **rounded** the format stores floating point with limited precision (single precision, or a few significant digits of text), so the values came back close but not equal; integers above 2**24 are not exact in it, which is the format's own limit. Writing such an array to one of these formats (`cae`, `ensight`, `frd`, `gid`, `gltf`, `marc_t19`, `radioss_anim`, `xplt`) warns once per array, in both engines.
- **dropped** the format does not carry that array.
- **error** the writer refuses the mesh and its message names the format.
- **not observed** an optional library the writer needs is not installed in the environment that generated the page.

A value that comes back as a *different integer* is a silent narrowing and is a defect: no row below says it, and `tests/python/test_id_widths.py` fails if one does.

| Format | Point array | Cell array |
| --- | --- | --- |
"""


def rows(table):
    out = []
    for fmt in sorted(table):
        e = table[fmt]
        if "error" in e:
            text = (
                e["error"] if e["error"] == "not observed" else f"error ({e['error']})"
            )
            out.append(f"| `{fmt}` | {text} | {text} |")
        else:
            out.append(f"| `{fmt}` | {e['point']} | {e['cell']} |")
    return "\n".join(out) + "\n"


IDS_HEADER = """
## Node and element ids

The ids a format stores for its nodes and elements, for the formats that take them through a data key of the mesh model (`tests/python/id_widths_spec.py`, `ID_KEYS`): the same probe with one distinct id of `2**31 + 5` and up per node and per cell, set as `abaqus:id`, `global:node_id`/`global:cell_id`, `libmesh:id`, `mdpa:id`, `med:num` or `radioss:node_id`/`radioss:element_id`. A format that is not listed renumbers its entities or takes ids only through its own numbering; its width is stated on its page instead: [CGNS](./formats/cgns.md) writes `I4` connectivity while the point count fits `int32` and `I8` after, [Exodus](./formats/exodus.md) has an `int64` mode, and [Gmsh 4.1](./formats/gmsh.md) stores tags as `size_t`.

| Format | Point ids | Cell ids |
| --- | --- | --- |
"""


def render(table, ids=None):
    text = HEADER + rows(table)
    if ids:
        text += IDS_HEADER + rows(ids)
    return text


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the page is stale"
    )
    parser.add_argument("--observe", action="store_true", help="print observed entries")
    args = parser.parse_args(argv)
    import id_widths_spec as spec

    if args.observe:
        observed = {}
        for fmt in sorted(spec.cs.SPEC):
            o = spec.observe(fmt)
            if o is not None:
                observed[fmt] = {k: v for k, v in o.items() if k != "named"}
        observed_ids = {}
        for fmt in sorted(spec.ID_KEYS):
            o = spec.observe_ids(fmt)
            if o is not None:
                observed_ids[fmt] = {k: v for k, v in o.items() if k != "named"}
        pprint.pprint(observed, width=100, sort_dicts=True)
        print("# ids")
        pprint.pprint(observed_ids, width=100, sort_dicts=True)
        return 0
    text = render(spec.EXPECTED, spec.EXPECTED_IDS)
    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else ""
        if current != text:
            print(
                f"{PAGE.relative_to(REPO)} is stale: run tools/gen_id_widths_table.py"
            )
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(REPO)} ({len(spec.EXPECTED)} formats)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
