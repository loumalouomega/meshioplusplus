def block(body: str, name: str) -> str:
    m = re.search(name + r"\s*=\s*\{(.*?)\};", body, re.S)
    if m is None:
        raise SystemExit(f"no '{name}' table")
    return m.group(1)


def nested(text: str) -> list[list[str]]:
    return [re.findall(r"[\w.]+", row) for row in re.findall(r"\{([^{}]*)\}", text)]


def parse(header: str, name: str) -> dict:
    m = re.search(r"namespace " + name + r"\s*\{(.*?)\n\}", header, re.S)
    if m is None:
        raise SystemExit(f"no scheme '{name}'")
    body = m.group(1)
    coords = [
        Fraction(x) * 20 for x in re.findall(r"-?\d*\.?\d+", block(body, "verts"))
    ]
    for c in coords:
        if c.denominator != 1 or not 0 <= c <= 20:
            raise SystemExit(
                f"{name}: coordinate {c / 20} is not a multiple of 1/20 in [0, 1]"
            )
    faces = [[int(v) for v in row] for row in nested(block(body, "faces"))]
    polys = [[int(f) for f in row] for row in nested(block(body, "polys"))]
    winding = [[w == "true" for w in row] for row in nested(block(body, "winding"))]
    nv = len(coords) // 3
    if len(coords) % 3 or any(v >= nv for f in faces for v in f):
        raise SystemExit(f"{name}: a face names a vertex the scheme does not have")
    if any(f >= len(faces) for p in polys for f in p):
        raise SystemExit(f"{name}: a cell names a face the scheme does not have")
    if [len(p) for p in polys] != [len(w) for w in winding]:
        raise SystemExit(f"{name}: the windings do not match the cells")
    return {
        "verts": [int(c) for c in coords],
        "faces": faces,
        "polys": polys,
        "winding": winding,
    }


def wrap(values: list, indent: str = "    ") -> str:
    out, line = [], ""
    for v in values:
        item = f"{v}, "
        if len(line) + len(item) > 92:
            out.append(indent + line.rstrip())
            line = ""
        line += item
    if line:
        out.append(indent + line.rstrip())
    return "\n".join(out)


def emit(schemes: list[tuple[str, dict]]) -> str:
    lines = [BANNER]
    lines.append("// Project includes")
    lines.append('#include "hex_dual_schemes.hpp"')
    lines.append("")
    lines.append("namespace meshioplusplus {")
    lines.append("namespace detail {")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    for cpp, s in schemes:
        ends_f, flat_f = [], []
        for f in s["faces"]:
            flat_f.extend(f)
            ends_f.append(len(flat_f))
        ends_p, flat_p, flat_w = [], [], []
        for p, w in zip(s["polys"], s["winding"]):
            flat_p.extend(p)
            flat_w.extend(int(x) for x in w)
            ends_p.append(len(flat_p))
        lines.append(f"constexpr std::int8_t kHds{cpp}Verts[] = {{")
        lines.append(wrap(s["verts"]))
        lines.append("};")
        lines.append(f"constexpr std::uint16_t kHds{cpp}Faces[] = {{")
        lines.append(wrap(flat_f))
        lines.append("};")
        lines.append(f"constexpr std::uint16_t kHds{cpp}FaceEnds[] = {{")
        lines.append(wrap(ends_f))
        lines.append("};")
        lines.append(f"constexpr std::uint16_t kHds{cpp}Polys[] = {{")
        lines.append(wrap(flat_p))
        lines.append("};")
        lines.append(f"constexpr std::uint16_t kHds{cpp}PolyEnds[] = {{")
        lines.append(wrap(ends_p))
        lines.append("};")
        lines.append(f"constexpr std::uint8_t kHds{cpp}Winding[] = {{")
        lines.append(wrap(flat_w))
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const HexDualScheme& hex_dual_scheme(HexTransition Type) {")
    lines.append("    static const HexDualScheme kTable[] = {")
    for cpp, s in schemes:
        lines.append(
            f"        {{kHds{cpp}Verts, {len(s['verts']) // 3}, kHds{cpp}Faces, "
            f"kHds{cpp}FaceEnds, {len(s['faces'])}, kHds{cpp}Polys, kHds{cpp}PolyEnds,"
        )
        lines.append(f"         {len(s['polys'])}, kHds{cpp}Winding}},")
    lines.append("    };")
    lines.append("    return kTable[static_cast<std::size_t>(Type)];")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace detail")
    lines.append("}  // namespace meshioplusplus")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("header", type=Path, help="CinoLib's hex_transition_schemes.h")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    header = args.header.read_text(encoding="utf-8")
    schemes = [(cpp, parse(header, name)) for name, cpp in SCHEMES]
    args.output.write_text(emit(schemes), encoding="utf-8")
    if shutil.which("clang-format"):
        subprocess.run(["clang-format", "-i", str(args.output)], check=True)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
