#!/usr/bin/env python3
"""Generate the built-in colormap lookup tables.

meshio++'s SVG/TikZ data-driven coloring maps a scalar through a colormap
without taking a dependency on matplotlib: the tables are baked into the core
as 256-entry uint8 LUTs. viridis and turbo are *defined* by matplotlib as
256-entry listed colormaps, so the LUT is the canonical data rather than an
approximation; coolwarm is a segmented map sampled at the same 256 points
matplotlib itself renders it at.

Three files come out of this, and are pinned against each other by
``tests/python/test_colormap.py`` (via the ``_core.colormap_table`` export), so a
hand-edit to any one of them fails CI:

- ``src/cpp/include/meshioplusplus/detail/colormap.hpp`` -- declarations only
  (`Rgb`, `kColormapSize`, the three function signatures). No table data, so
  every translation unit that includes it stays cheap to compile.
- ``src/cpp/src/detail/colormap.cpp`` -- the table data (file-private, in an
  anonymous namespace) and the function bodies. Mirrors the rest of
  `src/cpp/src/detail/`: a body that runs once per call (`colormap_table`,
  `colormap_names`) or once per face (`colormap_lookup`, the same "once per
  cell" bucket `FiniteStats`'s neighbours in `data_ops.hpp` document) belongs
  out of line, not inlined into every including TU.
- ``src/python/meshioplusplus/_colormap.py`` -- the Python twin. Python has no
  header/source split, so this one file carries both the tables and the
  functions, as before.

Regenerate with::

    python tools/gen_colormaps.py

matplotlib is needed to *regenerate*; the committed output is dependency-free.
"""

from __future__ import annotations

import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent

# Order is the user-facing order in error messages and CLI --cmap choices: the
# three original maps first (their tables are pinned by the SVG/TikZ/glTF byte
# tests), then the additions of v16.33.0 and `synthwave` (v16.38.0), then a
# reversed `_r` variant of each.
BASE_NAMES = [
    "viridis",
    "coolwarm",
    "turbo",
    "magma",
    "inferno",
    "plasma",
    "grey",
    "synthwave",
]
NAMES = BASE_NAMES + [n + "_r" for n in BASE_NAMES]

# Names whose matplotlib spelling differs.
MATPLOTLIB_NAME = {"grey": "gray", "grey_r": "gray_r"}

HPP_PATH = (
    REPO / "src" / "cpp" / "include" / "meshioplusplus" / "detail" / "colormap.hpp"
)
CPP_PATH = REPO / "src" / "cpp" / "src" / "detail" / "colormap.cpp"
PY_PATH = REPO / "src" / "python" / "meshioplusplus" / "_colormap.py"

GENERATED = "Generated by tools/gen_colormaps.py -- do not edit by hand."

