"""tools/cad_corpus.py (roadmap 6.5): the taxonomy, the fetch's hash checks,
one model run end to end, the compare gate and the freshness of the
published table. No network: sources are file:// URLs."""

import importlib.util
import json
import pathlib

import pytest

import meshioplusplus as mio

try:
    from meshioplusplus import _core
except ImportError:  # pragma: no cover - the numpy-only install
    _core = None

ROOT = pathlib.Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location(
    "cad_corpus", ROOT / "tools" / "cad_corpus.py"
)
corpus = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(corpus)

needs_occt = pytest.mark.skipif(
    not getattr(_core, "__has_occt__", False), reason="needs the OpenCASCADE backend"
)


@pytest.mark.parametrize(
    "status, reason, expected",
    [
        (
            "projection_failed",
            "the trims of one edge are 0.01 apart",
            "gap_beyond_tolerance",
        ),
        (
            "unsupported",
            "its trims leave its surface's parameter range",
            "trim_outside_patch",
        ),
        ("self_intersecting", "its boundary crosses itself", "self_intersecting_loop"),
        ("open_loop", "its loops do not bound a domain consistently", "open_loop"),
        (
            "degenerate",
            "two distinct boundary points have the same parameters",
            "degenerate_patch",
        ),
        ("empty", "its loops enclose no area", "degenerate_patch"),
        ("budget_exceeded", "more points than max_points", "budget"),
        ("other", "an embedded edge could not be recovered", "other"),
    ],
)
def test_every_failure_has_a_class(status, reason, expected):
    assert corpus.classify(status, reason) == expected
    assert expected in corpus.CLASSES


def _manifest(tmp_path, files, sample=None):
    source = {
        "id": "local",
        "kind": "https",
        "url": (tmp_path / "src" / files[0][0]).as_uri(),
        "licence": "generated by the test",
        "models": [
            {"id": "local/" + name, "path": name, "sha256": digest}
            for name, digest in files
        ],
    }
    if sample:
        source["sample"] = sample
    path = tmp_path / "manifest.json"
    path.write_text(json.dumps({"Version": 1, "sources": [source]}))
    return path


def test_fetch_records_missing_hashes_and_refuses_wrong_ones(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.step").write_text("not a model\n")
    manifest = _manifest(tmp_path, [("a.step", None)])
    record = tmp_path / "hashes.json"
    assert (
        corpus.main(
            [
                "fetch",
                "--manifest",
                str(manifest),
                "--dest",
                str(tmp_path / "d"),
                "--record",
                str(record),
            ]
        )
        == 0
    )
    recorded = json.loads(record.read_text())
    assert recorded == {"local/a.step": corpus.sha256(tmp_path / "src" / "a.step")}
    manifest = _manifest(tmp_path, [("a.step", "0" * 64)])
    assert (
        corpus.main(
            ["fetch", "--manifest", str(manifest), "--dest", str(tmp_path / "d")]
        )
        == 1
    )
    # A mismatched file is removed, so a run reports it unavailable.
    assert not (tmp_path / "d" / "local" / "a.step").exists()


def test_a_source_that_cannot_be_reached_is_not_fatal(tmp_path):
    manifest = _manifest(tmp_path, [("missing.step", None)])
    assert (
        corpus.main(
            ["fetch", "--manifest", str(manifest), "--dest", str(tmp_path / "d")]
        )
        == 0
    )
    out = tmp_path / "run.json"
    assert (
        corpus.main(
            [
                "run",
                "--manifest",
                str(manifest),
                "--dest",
                str(tmp_path / "d"),
                "--out",
                str(out),
            ]
        )
        == 0
    )
    assert json.loads(out.read_text())["models"][0]["status"] == "unavailable"


def test_the_seeded_sample_is_the_same_every_time():
    source = {
        "models": [{"id": f"m{i:03d}"} for i in range(50)],
        "sample": {"seed": 7, "count": 5},
    }
    first = [m["id"] for m in corpus.selected(source)]
    assert len(first) == 5 and first == sorted(first)
    assert first == [m["id"] for m in corpus.selected(source)]


@needs_occt
def test_one_model_end_to_end(tmp_path):
    (tmp_path / "src").mkdir()
    step = tmp_path / "src" / "box.step"
    mio.write(step, mio.extract_surface(mio.box()))
    manifest = _manifest(tmp_path, [("box.step", corpus.sha256(step))])
    dest = tmp_path / "d"
    assert corpus.main(["fetch", "--manifest", str(manifest), "--dest", str(dest)]) == 0
    out = tmp_path / "run.json"
    assert (
        corpus.main(
            [
                "run",
                "--manifest",
                str(manifest),
                "--dest",
                str(dest),
                "--out",
                str(out),
                "--size-divisor",
                "10",
            ]
        )
        == 0
    )
    run = json.loads(out.read_text())
    row = run["models"][0]
    assert row["status"] == "ok", row
    assert row["faces"] == row["faces_ok"] == 6
    assert row["failures_by_class"] == {} and row["num_open_edges"] == 0
    assert row["area_ratio"] == pytest.approx(1.0, rel=1e-9)
    assert row["hausdorff_to_brepmesh"] < 1e-9
    for key in (
        "read_s",
        "mesh_s",
        "peak_rss_mb",
        "wall_s",
        "quality",
        "min_angle_deg",
    ):
        assert key in row
    # The baseline it makes passes against the run; a model that stops
    # meshing fails the gate by name.
    base = tmp_path / "baseline.json"
    assert corpus.main(["baseline", str(out), "--out", str(base)]) == 0
    assert corpus.main(["compare", str(out), "--baseline", str(base)]) == 0
    row.update(status="timeout", faces_ok=0)
    out.write_text(json.dumps(run))
    assert corpus.main(["compare", str(out), "--baseline", str(base)]) == 1


def test_compare_names_the_model_that_stopped_meshing(tmp_path, capsys):
    base = {
        "Version": 1,
        "models": {
            "s/a": {"status": "ok", "meshed": True, "faces": 3, "faces_ok": 3},
            "s/b": {"status": "ok", "meshed": False, "faces": 3, "faces_ok": 2},
            "s/c": {"status": "ok", "meshed": True, "faces": 1, "faces_ok": 1},
        },
    }
    run = {
        "models": [
            {"id": "s/a", "status": "ok", "faces": 3, "faces_ok": 2},
            {"id": "s/b", "status": "ok", "faces": 3, "faces_ok": 3},
            {"id": "s/c", "status": "unavailable"},
        ]
    }
    (tmp_path / "b.json").write_text(json.dumps(base))
    (tmp_path / "r.json").write_text(json.dumps(run))
    assert (
        corpus.main(
            [
                "compare",
                str(tmp_path / "r.json"),
                "--baseline",
                str(tmp_path / "b.json"),
            ]
        )
        == 1
    )
    text = capsys.readouterr().out
    assert "REGRESSION: s/a" in text
    assert "s/b: meshes now" in text
    assert "s/c: not measured" in text


def test_the_published_table_is_fresh():
    assert corpus.main(["table", "--check"]) == 0
