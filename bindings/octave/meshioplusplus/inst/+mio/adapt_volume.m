function r = adapt_volume(mesh, varargin)
%ADAPT_VOLUME  Remesh a tetrahedral mesh to a graded size field.
%   R = mio.adapt_volume(MESH, ...) collapses, splits, swaps and smooths a
%   tet-only mesh towards a graded isotropic size field under a bound on how
%   far the boundary moves, keeping corners, ridges, materials, regions and
%   boundary tags. Options: 'hmin' (0: automatic), 'hmax' (0: automatic),
%   'hgrad' (1.3), 'hausd' (0: 1e-3 of the diagonal), 'hausd_relative'
%   (false), 'size_array' (''), 'preserve_boundary' (false),
%   'preserve_features' (true), 'quality_metric' ('min_dihedral',
%   'mean_ratio' or 'amips'), 'quality_min' (-1: the default), 'max_iterations'
%   (10), 'collapse', 'split', 'swap' and 'smooth' (true), 'boundary_sizing'
%   ('input' keeps the boundary's resolution, 'geometry' sizes it by
%   curvature). Returns a struct:
%   mesh and every counter of the report (num_tets_before, num_tets_after,
%   ..., max_boundary_deviation, hmin, hmax, hausd, volume_before,
%   volume_after). See doc/adapt_volume.md.

    o = mio.internal.opts(varargin, {'hmin', 0, 'hmax', 0, 'hgrad', 1.3, 'hausd', 0, ...
        'hausd_relative', false, 'size_array', '', 'preserve_boundary', false, ...
        'preserve_features', true, 'quality_metric', 'min_dihedral', 'quality_min', -1, ...
        'max_iterations', 10, 'collapse', true, 'split', true, 'swap', true, ...
        'smooth', true, 'boundary_sizing', 'input'}, 'mio.adapt_volume');
    r = meshioplusplus_mex('mio_adapt_volume', mesh, double(o.hmin), double(o.hmax), ...
        double(o.hgrad), double(o.hausd), logical(o.hausd_relative), ...
        mio.internal.str(o.size_array, 'size_array'), logical(o.preserve_boundary), ...
        logical(o.preserve_features), mio.internal.str(o.quality_metric, 'quality_metric'), ...
        double(o.quality_min), double(o.max_iterations), logical(o.collapse), ...
        logical(o.split), logical(o.swap), logical(o.smooth), ...
        mio.internal.str(o.boundary_sizing, 'boundary_sizing'));
end
