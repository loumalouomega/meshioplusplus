function m = od_generate(shape, counts, varargin)
%OD_GENERATE  The shared entry point of the parametric generators.
%   M = mio.internal.od_generate(SHAPE, COUNTS, ...) with the options, in
%   order, 'size' ([1 1 1]), 'origin' ([0 0 0]), 'radius' (1), 'height' (1),
%   'cell_type' (''), 'split' ('zigzag'), 'order' (1), 'max_cells'
%   (20000000), 'radius2' (0.5), 'angle' (2*pi), 'num_twists' (1),
%   'complete' (false), 'ratio' (1) and 'seed' (0) -- the R binding's
%   mio_generate_.

    o = mio.internal.opts(varargin, {'size', [1 1 1], 'origin', [0 0 0], 'radius', 1, ...
        'height', 1, 'cell_type', '', 'split', 'zigzag', 'order', 1, 'max_cells', 20000000, ...
        'radius2', 0.5, 'angle', 2 * pi, 'num_twists', 1, 'complete', false, 'ratio', 1, ...
        'seed', 0}, 'mio.internal.od_generate');
    m = meshioplusplus_mex('mio_generate', mio.internal.str(shape, 'shape'), double(counts), ...
        double(o.size), double(o.origin), double(o.radius), double(o.height), ...
        mio.internal.str(o.cell_type, 'cell_type'), mio.internal.str(o.split, 'split'), ...
        double(o.order), double(o.max_cells), double(o.radius2), double(o.angle), ...
        double(o.num_twists), logical(o.complete), double(o.ratio), double(o.seed));
end
