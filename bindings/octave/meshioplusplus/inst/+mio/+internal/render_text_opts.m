function t = render_text_opts(o)
%RENDER_TEXT_OPTS  The text options of mio.render_text / mio.write_snapshot
%   as the name/value cell the MEX takes, normalised as the R binding does.

    t = {'encoding', mio.internal.str(o.encoding, 'encoding'), ...
        'color_depth', mio.internal.str(o.color_depth, 'color_depth'), ...
        'format', mio.internal.str(o.format, 'format'), 'cols', double(o.cols), ...
        'rows', double(o.rows), 'cell_aspect', double(o.cell_aspect), ...
        'tmux', logical(o.tmux), 'notes', logical(o.notes)};
end
