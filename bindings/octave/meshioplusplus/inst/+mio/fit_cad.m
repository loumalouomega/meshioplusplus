function r = fit_cad(mesh, varargin)
%FIT_CAD  Turn the fitted patches of a closed skin into a CAD solid.
%   R = mio.fit_cad(MESH, ...) builds a solid from the fitted patches (plane,
%   sphere, cylinder, cone, torus, fillet/blend, helical thread and freeform
%   B-spline faces; the rest coplanar polygons) through OpenCASCADE, or the
%   kernel-free native backend without it (see mio.has_occt). Without
%   'segment:patch', segment and fit_primitives run first. See
%   doc/fit_cad.md. Options (R defaults):
%     'step_path' ('': write nothing), 'tolerance' (0), 'exact_edges' (true),
%     'types' (cellstr; all five primitives), 'mesh_deflection' (0),
%     'max_demotion_rounds' (8), 'freeform' (true), 'freeform_degree' (3),
%     'freeform_max_control' (64), 'freeform_split' (true), 'fillets' (true),
%     'threads' (true), 'merge_faces' (true), 'backend' ('auto', 'occt' or
%     'native'), 'refine_segmentation' (false), 'max_refine_iterations' (10),
%     'refine_epsilon' (1e-3), 'normal_weight' (1), 'allow_merge' (true),
%     'allow_split' (true), 'ransac_seed' ([]), 'refine_tolerance' (1e-3),
%     'relative_tolerance' (true), 'freeform_general' (false),
%     'freeform_tolerance' (0), 'freeform_smoothing' (1e-12),
%     'max_freeform_poles' (40), 'max_freeform_iterations' (30),
%     'max_freeform_splits' (2), 'sew_tolerance' (0), 'extend_surfaces'
%     (false), 'snap_junctions' (false), 'face_deviation' (false),
%     'freeform_mode' ('legacy', 'adaptive', 'network' or 'auto'),
%     'freeform_parameterization' ('auto', 'projection', 'lscm' or
%     'harmonic'), 'extraordinary_vertex' ('g0', 'g1', 'g1x' or 'g1xx';
%     'g1x'), 'local_refine' ('knots' or 'thb'), 'freeform_g1_tolerance_deg'
%     (1), 'freeform_max_control_points' (400), 'layout_target_patch_size'
%     (0.1), 'layout_max_valence_deviation' (2), 'resegment_rounds' (2),
%     'layout_snap_to_features' (true), 'validate_by_surface_sampling' (true),
%     'constrain_primitives' (false), 'validation_report' (false),
%     'validation_acceptance' (false), 'freeform_fit_schedule' ('legacy' or
%     'continuation'), 'freeform_objective' ('default', 'pdm', 'tdm' or
%     'sdm') and 'kinematic_surfaces' (false: true first tries a patch no
%     primitive explains as a surface of linear extrusion, of revolution or a
%     helical surface).
%   Returns a struct: mesh (with cell data 'fit_cad:face', 'fit_cad:type' and
%   'fit_cad:patch'), valid, tolerance, volume, skin_volume, volume_ratio,
%   max_deviation, num_faces, num_plane, num_sphere, num_cylinder, num_cone,
%   num_torus, num_faceted_faces, num_patches, num_demoted, num_exact_edges,
%   num_approx_edges, num_solids, num_bspline, num_split_patches, num_fillet,
%   num_helical, num_variable_fillet, num_blend, num_rounded_thread,
%   num_vertex_blend, num_chamfer, num_conic_blend, num_tapered_thread,
%   num_variable_pitch_thread, backend, refined, refine_iterations,
%   num_refine_splits, num_refine_merges, initial_explained_area_fraction,
%   explained_area_fraction, closed, num_freeform_general,
%   num_freeform_refinements, avg_freeform_poles, num_extended_edges,
%   num_snapped_junctions, hausdorff_max, hausdorff_rms (NaN unless
%   'face_deviation' measured them), refinement_kept, brep_checked,
%   freeform_mode, facet_area_fraction, num_freeform_adaptive,
%   num_network_patches, num_network_edges, num_extraordinary_vertices,
%   num_resegmented, num_escalations, max_g1_angle_deg,
%   max_freeform_distance, rms_freeform_distance, num_face_records,
%   num_constrained_primitives, num_constraint_groups and the validation
%   report: validation_reported, cad_to_mesh_max, cad_to_mesh_p95,
%   cad_to_mesh_p99, mesh_to_cad_max, mesh_to_cad_p95, mesh_to_cad_p99,
%   normal_deviation_max_deg, normal_deviation_p95_deg,
%   step_round_trip_checked, step_round_trip_valid,
%   step_round_trip_volume_ratio and total_freeform_control_points (NaN and
%   false unless 'validation_report' measured them), num_extrusion,
%   num_revolution and num_kinematic_helical.

    o = mio.internal.opts(varargin, {'step_path', '', 'tolerance', 0, 'exact_edges', true, ...
        'types', {'plane', 'sphere', 'cylinder', 'cone', 'torus'}, 'mesh_deflection', 0, ...
        'max_demotion_rounds', 8, 'freeform', true, 'freeform_degree', 3, ...
        'freeform_max_control', 64, 'freeform_split', true, 'fillets', true, ...
        'threads', true, 'merge_faces', true, 'backend', 'auto', ...
        'refine_segmentation', false, 'max_refine_iterations', 10, 'refine_epsilon', 1e-3, ...
        'normal_weight', 1, 'allow_merge', true, 'allow_split', true, 'ransac_seed', [], ...
        'refine_tolerance', 1e-3, 'relative_tolerance', true, 'freeform_general', false, ...
        'freeform_tolerance', 0, 'freeform_smoothing', 1e-12, 'max_freeform_poles', 40, ...
        'max_freeform_iterations', 30, 'max_freeform_splits', 2, 'sew_tolerance', 0, ...
        'extend_surfaces', false, 'snap_junctions', false, 'face_deviation', false, ...
        'freeform_mode', 'legacy', 'freeform_parameterization', 'auto', ...
        'extraordinary_vertex', 'g1x', 'local_refine', 'knots', ...
        'freeform_g1_tolerance_deg', 1, 'freeform_max_control_points', 400, ...
        'layout_target_patch_size', 0.1, 'layout_max_valence_deviation', 2, ...
        'resegment_rounds', 2, 'layout_snap_to_features', true, ...
        'validate_by_surface_sampling', true, 'constrain_primitives', false, ...
        'validation_report', false, 'validation_acceptance', false, ...
        'freeform_fit_schedule', 'legacy', 'freeform_objective', 'default', ...
        'kinematic_surfaces', false}, 'mio.fit_cad');
    if isempty(o.ransac_seed)
        seed = [];
    else
        seed = double(o.ransac_seed);
    end
    r = meshioplusplus_mex('mio_fit_cad', mesh, mio.internal.str(o.step_path, 'step_path'), ...
        double(o.tolerance), logical(o.exact_edges), types_mask(o.types, 'fit_cad'), ...
        double(o.mesh_deflection), double(o.max_demotion_rounds), logical(o.freeform), ...
        double(o.freeform_degree), double(o.freeform_max_control), logical(o.freeform_split), ...
        logical(o.fillets), logical(o.threads), logical(o.merge_faces), ...
        mio.internal.str(o.backend, 'backend'), logical(o.refine_segmentation), ...
        double(o.max_refine_iterations), double(o.refine_epsilon), double(o.normal_weight), ...
        logical(o.allow_merge), logical(o.allow_split), seed, double(o.refine_tolerance), ...
        logical(o.relative_tolerance), logical(o.freeform_general), ...
        double(o.freeform_tolerance), double(o.freeform_smoothing), ...
        double(o.max_freeform_poles), double(o.max_freeform_iterations), ...
        double(o.max_freeform_splits), double(o.sew_tolerance), logical(o.extend_surfaces), ...
        logical(o.snap_junctions), logical(o.face_deviation), ...
        mio.internal.str(o.freeform_mode, 'freeform_mode'), ...
        mio.internal.str(o.freeform_parameterization, 'freeform_parameterization'), ...
        mio.internal.str(o.extraordinary_vertex, 'extraordinary_vertex'), ...
        mio.internal.str(o.local_refine, 'local_refine'), ...
        double(o.freeform_g1_tolerance_deg), double(o.freeform_max_control_points), ...
        double(o.layout_target_patch_size), double(o.layout_max_valence_deviation), ...
        double(o.resegment_rounds), logical(o.layout_snap_to_features), ...
        logical(o.validate_by_surface_sampling), logical(o.constrain_primitives), ...
        logical(o.validation_report), logical(o.validation_acceptance), ...
        mio.internal.str(o.freeform_fit_schedule, 'freeform_fit_schedule'), ...
        mio.internal.str(o.freeform_objective, 'freeform_objective'), ...
        logical(o.kinematic_surfaces));
end

function mask = types_mask(types, fname)
% The primitive bit mask: plane 2, sphere 4, cylinder 8, cone 16, torus 32.
    known = {'plane', 'sphere', 'cylinder', 'cone', 'torus'};
    if isempty(types)
        mask = 0;
        return;
    end
    types = mio.internal.cellstr_arg(types, 'types');
    bad = types(~ismember(types, known));
    if ~isempty(bad)
        error('meshioplusplus:argument', 'meshio++: %s: unknown primitive type %s', fname, bad{1});
    end
    [~, loc] = ismember(unique(types), known);
    mask = sum(2 .^ loc);
end
