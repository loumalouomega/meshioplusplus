const std::uint8_t* colormap_table(const std::string& rName) {
    if (rName == "viridis")
        return kViridis;
    if (rName == "coolwarm")
        return kCoolwarm;
    if (rName == "turbo")
        return kTurbo;
    if (rName == "magma")
        return kMagma;
    if (rName == "inferno")
        return kInferno;
    if (rName == "plasma")
        return kPlasma;
    if (rName == "grey")
        return kGrey;
    if (rName == "viridis_r")
        return kViridisR;
    if (rName == "coolwarm_r")
        return kCoolwarmR;
    if (rName == "turbo_r")
        return kTurboR;
    if (rName == "magma_r")
        return kMagmaR;
    if (rName == "inferno_r")
        return kInfernoR;
    if (rName == "plasma_r")
        return kPlasmaR;
    if (rName == "grey_r")
        return kGreyR;
    throw std::invalid_argument("meshio++: unknown colormap '" + rName +
                                "' (available: viridis, coolwarm, turbo, magma, inferno, plasma, grey, viridis_r, coolwarm_r, turbo_r, magma_r, inferno_r, plasma_r, grey_r)");
}

